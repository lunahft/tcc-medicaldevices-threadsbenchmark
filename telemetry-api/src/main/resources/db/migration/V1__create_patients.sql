CREATE TABLE telemetry.patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_code VARCHAR(64) NOT NULL,
    unit_code VARCHAR(32) NOT NULL,
    bed_code VARCHAR(32) NOT NULL,
    status VARCHAR(20) NOT NULL,
    admitted_at TIMESTAMPTZ NOT NULL,
    discharged_at TIMESTAMPTZ,

    CONSTRAINT uk_patients_patient_code
        UNIQUE (patient_code),

    CONSTRAINT ck_patients_status
        CHECK (status IN ('ACTIVE', 'DISCHARGED', 'INACTIVE')),

    CONSTRAINT ck_patients_discharge_time
        CHECK (
            discharged_at IS NULL
            OR discharged_at >= admitted_at
        ),

    CONSTRAINT ck_patients_discharge_state
        CHECK (
            (status = 'DISCHARGED' AND discharged_at IS NOT NULL)
            OR
            (status <> 'DISCHARGED' AND discharged_at IS NULL)
        )
);